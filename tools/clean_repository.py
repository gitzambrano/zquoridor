#!/usr/bin/env python3
"""Clean ephemeral caches, bytecode, and aborted staging files from the repository.

This tool safely reclaims disk space by removing only reproducible, transient,
or aborted artifacts. It preserves tracked files, canonical datasets, weights,
checkpoints, browser profiles, and external bots.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import stat
import subprocess
import sys
from typing import Dict, List, Set, Tuple

ROOT = Path(__file__).resolve().parents[1]

CONFIG = {
    "root": ROOT,
    "clean_pycache": True,
    "clean_input_cache": True,
    "clean_staging_interrupted": True,
    "clean_transient_recovery": True,
    "dry_run": False,
    "verbose": False,
}

PROTECTED_PARTS = {
    ".git",
    "profiles",
    "external_bots",
    ".toolchain",
}


def _remove_readonly(func, path, exc_info):
    """Clear the read-only bit and retry the removal."""
    try:
        os.chmod(path, stat.S_IWRITE)
        func(path)
    except Exception:
        pass


def get_tracked_files(root: Path) -> Set[Path]:
    """Return a set of absolute paths tracked by Git."""
    try:
        out = subprocess.check_output(
            ["git", "ls-files", "-z"],
            cwd=root,
            stderr=subprocess.DEVNULL,
        ).decode("utf-8", errors="ignore")
        return {root / item for item in out.split("\0") if item}
    except Exception:
        return set()


def is_protected(path: Path, tracked: Set[Path]) -> bool:
    """Check if a path is protected from deletion."""
    if path in tracked:
        return True
    parts = set(path.parts)
    if any(p in parts for p in PROTECTED_PARTS):
        return True
    # Extra protection for credentials or private config
    if path.name in ("private.py", "COLAB_ACCOUNTS.json"):
        return True
    return False


def _safe_dir_size(path: Path) -> int:
    """Calculate directory size safely, ignoring broken links or transient files."""
    total = 0
    try:
        for r, _, files in os.walk(path):
            for f in files:
                try:
                    total += (Path(r) / f).stat().st_size
                except (OSError, FileNotFoundError):
                    pass
    except Exception:
        pass
    return total


def collect_pycache(root: Path, tracked: Set[Path]) -> Tuple[List[Path], int]:
    """Find all __pycache__ and .pytest_cache directories."""
    dirs_to_delete: List[Path] = []
    total_bytes = 0

    for dirpath, dirnames, filenames in os.walk(root):
        current = Path(dirpath)
        # Never descend into .git or junctions
        if ".git" in current.parts or current.is_symlink():
            dirnames.clear()
            continue

        for d in list(dirnames):
            if d in ("__pycache__", ".pytest_cache"):
                dp = current / d
                if not is_protected(dp, tracked):
                    size = _safe_dir_size(dp)
                    dirs_to_delete.append(dp)
                    total_bytes += size
                    dirnames.remove(d)

    return dirs_to_delete, total_bytes


def collect_input_caches(root: Path, tracked: Set[Path]) -> Tuple[List[Path], int]:
    """Find all .input_cache directories generated by mix_experimental_datasets."""
    dirs_to_delete: List[Path] = []
    total_bytes = 0

    # Specifically search experimental and results
    for candidate_root in [root / "experimental", root / "results"]:
        if not candidate_root.is_dir():
            continue
        for dirpath, dirnames, filenames in os.walk(candidate_root):
            current = Path(dirpath)
            if current.is_symlink() or ".git" in current.parts:
                dirnames.clear()
                continue
            for d in list(dirnames):
                if d == ".input_cache":
                    dp = current / d
                    if not is_protected(dp, tracked):
                        size = _safe_dir_size(dp)
                        dirs_to_delete.append(dp)
                        total_bytes += size
                        dirnames.remove(d)

    # Deduplicate in case results/experiments is a junction to experimental/experiments
    unique_dirs: List[Path] = []
    seen_canonical = set()
    for d in dirs_to_delete:
        try:
            real = d.resolve()
            if real not in seen_canonical:
                seen_canonical.add(real)
                unique_dirs.append(d)
        except Exception:
            unique_dirs.append(d)

    return unique_dirs, total_bytes


def collect_staging_interrupted(root: Path, tracked: Set[Path]) -> Tuple[List[Path], int]:
    """Find interrupted directories and .tmp files in selfplay staging."""
    items_to_delete: List[Path] = []
    total_bytes = 0

    selfplay_dir = root / "data" / "selfplay"
    if not selfplay_dir.is_dir():
        return items_to_delete, total_bytes

    for dirpath, dirnames, filenames in os.walk(selfplay_dir):
        current = Path(dirpath)
        if "staging" in current.parts:
            # Check for interrupted folders
            for d in list(dirnames):
                if d.startswith("interrupted_"):
                    dp = current / d
                    if not is_protected(dp, tracked):
                        size = _safe_dir_size(dp)
                        items_to_delete.append(dp)
                        total_bytes += size
                        dirnames.remove(d)

            # Check for .tmp files in staging
            for f in filenames:
                if f.endswith(".tmp"):
                    fp = current / f
                    if not is_protected(fp, tracked):
                        total_bytes += fp.stat().st_size
                        items_to_delete.append(fp)

    return items_to_delete, total_bytes


def collect_transient_recovery(root: Path, tracked: Set[Path]) -> Tuple[List[Path], int]:
    """Find stale recovery dumps and temporary backup files in selfplay."""
    files_to_delete: List[Path] = []
    total_bytes = 0

    selfplay_dir = root / "data" / "selfplay"
    if not selfplay_dir.is_dir():
        return files_to_delete, total_bytes

    for dirpath, dirnames, filenames in os.walk(selfplay_dir):
        current = Path(dirpath)
        for f in filenames:
            # Specific stale recovery files
            if f.endswith(".recovery.bak") or (f.startswith("manifest-recovery-") and f.endswith(".tmp")):
                fp = current / f
                if not is_protected(fp, tracked):
                    total_bytes += fp.stat().st_size
                    files_to_delete.append(fp)

    return files_to_delete, total_bytes


def clean_repository(config: Dict) -> Dict:
    """Execute cleanup according to configuration."""
    root = Path(config["root"]).resolve()
    dry_run = bool(config.get("dry_run", False))
    verbose = bool(config.get("verbose", False))

    tracked = get_tracked_files(root)

    actions: List[Dict] = []
    total_reclaimed_bytes = 0

    # 1. Bytecode caches
    if config.get("clean_pycache", True):
        pycache_dirs, b_size = collect_pycache(root, tracked)
        for p in pycache_dirs:
            actions.append({"category": "pycache", "path": p, "is_dir": True})
        total_reclaimed_bytes += b_size

    # 2. Input caches (.input_cache)
    if config.get("clean_input_cache", True):
        input_dirs, in_size = collect_input_caches(root, tracked)
        for p in input_dirs:
            actions.append({"category": "input_cache", "path": p, "is_dir": True})
        total_reclaimed_bytes += in_size

    # 3. Staging interrupted
    if config.get("clean_staging_interrupted", True):
        staging_items, st_size = collect_staging_interrupted(root, tracked)
        for p in staging_items:
            actions.append({"category": "staging_interrupted", "path": p, "is_dir": p.is_dir()})
        total_reclaimed_bytes += st_size

    # 4. Transient recovery
    if config.get("clean_transient_recovery", True):
        recovery_files, rec_size = collect_transient_recovery(root, tracked)
        for p in recovery_files:
            actions.append({"category": "transient_recovery", "path": p, "is_dir": False})
        total_reclaimed_bytes += rec_size

    # Execute removal if not dry run
    deleted_count = 0
    if not dry_run:
        for action in actions:
            target = action["path"]
            if not target.exists():
                continue
            try:
                if action["is_dir"]:
                    shutil.rmtree(target, onerror=_remove_readonly)
                else:
                    target.unlink(missing_ok=True)
                deleted_count += 1
                if verbose:
                    print(f"Removed [{action['category']}]: {target}")
            except Exception as e:
                print(f"Warning: failed to remove {target}: {e}", file=sys.stderr)
    else:
        deleted_count = len(actions)
        if verbose:
            for action in actions:
                print(f"Would remove [{action['category']}]: {action['path']}")

    summary = {
        "dry_run": dry_run,
        "items_found": len(actions),
        "items_deleted": deleted_count if not dry_run else 0,
        "bytes_reclaimed": total_reclaimed_bytes,
        "mb_reclaimed": round(total_reclaimed_bytes / (1024 * 1024), 2),
        "gb_reclaimed": round(total_reclaimed_bytes / (1024 ** 3), 3),
    }

    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="Report what would be cleaned without removing files")
    parser.add_argument("--verbose", action="store_true", help="Print details for every cleaned item")
    parser.add_argument("--skip-pycache", action="store_true", help="Skip removing Python bytecode caches")
    parser.add_argument("--skip-input-cache", action="store_true", help="Skip removing .input_cache directories")
    parser.add_argument("--skip-staging", action="store_true", help="Skip removing interrupted staging shards")
    parser.add_argument("--skip-recovery", action="store_true", help="Skip removing transient recovery dumps")
    parser.add_argument("--show-config", action="store_true", help="Display CONFIG as JSON and exit")

    args = parser.parse_args()

    if args.show_config:
        print(json.dumps(CONFIG, default=str, indent=2))
        return 0

    cfg = dict(CONFIG)
    if args.dry_run:
        cfg["dry_run"] = True
    if args.verbose:
        cfg["verbose"] = True
    if args.skip_pycache:
        cfg["clean_pycache"] = False
    if args.skip_input_cache:
        cfg["clean_input_cache"] = False
    if args.skip_staging:
        cfg["clean_staging_interrupted"] = False
    if args.skip_recovery:
        cfg["clean_transient_recovery"] = False

    mode = "Dry run" if cfg["dry_run"] else "Cleaning"
    print(f"Starting repository cleanup ({mode})...")

    result = clean_repository(cfg)

    action_verb = "Would reclaim" if cfg["dry_run"] else "Reclaimed"
    print(
        f"Done: {result['items_found']} target(s). "
        f"{action_verb} {result['mb_reclaimed']:.2f} MB ({result['gb_reclaimed']:.3f} GB)."
    )

    return 0


if __name__ == "__main__":
    sys.exit(main())
